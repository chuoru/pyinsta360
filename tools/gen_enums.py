#!/usr/bin/env python3
"""Generate pybind11 enum bindings and type stubs from the Insta360 SDK headers.

Only enumerator names are read from the headers; no header text is copied.
Aliases (`A = B`) are emitted like any other enumerator and marked in the
output, so the C++ compiler resolves their values.

    python tools/gen_enums.py --sdk-dir $INSTA360_SDK_DIR          # rewrite
    python tools/gen_enums.py --sdk-dir $INSTA360_SDK_DIR --check  # exit 1 on drift
"""
import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INC_OUT = ROOT / "src" / "enums_gen.inc"
PYI_OUT = ROOT / "python" / "pyinsta360" / "_sdk_enums.pyi"

# (header relative to include/, C++ enum name, Python name)
ENUMS = [
    ("camera/ins_types.h", "CameraType", "CameraType"),
    ("camera/ins_types.h", "ConnectionType", "ConnectionType"),
    ("camera/ins_types.h", "VideoEncodeType", "VideoEncodeType"),
    ("camera/ins_types.h", "CameraLensType", "CameraLensType"),
    ("camera/ins_types.h", "LogLevel", "LogLevel"),
    ("camera/ins_types.h", "CardState", "CardState"),
    ("camera/ins_types.h", "CardLocation", "CardLocation"),
    ("camera/ins_types.h", "RawCaptureType", "RawCaptureType"),
    ("camera/photography_settings.h", "CameraFunctionMode", "CameraFunctionMode"),
    ("camera/photography_settings.h", "VideoResolution", "VideoResolution"),
    ("camera/photography_settings.h", "PhotographyOptions_ExposureMode", "ExposureMode"),
    ("camera/photography_settings.h", "PowerType", "PowerType"),
]

_BLOCK_COMMENT = re.compile(r"/\*.*?\*/", re.S)
_LINE_COMMENT = re.compile(r"//[^\n]*")
_IDENT = re.compile(r"^[A-Za-z_]\w*$")


def parse_enum(text, cpp_name):
    """Return [(enumerator, alias_target_or_None)] in declaration order."""
    text = _LINE_COMMENT.sub("", _BLOCK_COMMENT.sub("", text))
    m = re.search(r"\benum\s+(?:class\s+)?%s\s*\{(.*?)\}" % re.escape(cpp_name), text, re.S)
    if not m:
        raise SystemExit("enum %s not found in header" % cpp_name)
    items = []
    for raw in m.group(1).split(","):
        raw = raw.strip()
        if not raw:
            continue
        name, _, expr = (p.strip() for p in raw.partition("="))
        if not _IDENT.match(name):
            raise SystemExit("cannot parse enumerator %r of %s" % (raw, cpp_name))
        items.append((name, expr if _IDENT.match(expr) else None))
    return items


def generate(sdk_dir):
    include = Path(sdk_dir) / "include"
    headers = {}
    inc = ["// Generated by tools/gen_enums.py. Do not edit.", ""]
    pyi = [
        "# Generated by tools/gen_enums.py. Do not edit.",
        "from typing import ClassVar, Dict",
        "",
        "class _Enum:",
        "    def __init__(self, value: int) -> None: ...",
        "    def __int__(self) -> int: ...",
        "    def __index__(self) -> int: ...",
        "    @property",
        "    def name(self) -> str: ...",
        "    @property",
        "    def value(self) -> int: ...",
        "",
    ]
    for header, cpp_name, py_name in ENUMS:
        if header not in headers:
            headers[header] = (include / header).read_text(encoding="utf-8-sig")
        items = parse_enum(headers[header], cpp_name)
        inc.append("py::enum_<ins_camera::%s>(m, \"%s\")" % (cpp_name, py_name))
        pyi.append("class %s(_Enum):" % py_name)
        pyi.append("    __members__: ClassVar[Dict[str, %s]]" % py_name)
        for name, alias in items:
            note = "  // alias of %s" % alias if alias else ""
            inc.append("    .value(\"%s\", ins_camera::%s::%s)%s" % (name, cpp_name, name, note))
            pyi.append("    %s: ClassVar[%s]" % (name, py_name))
        inc.append("    ;")
        inc.append("")
        pyi.append("")
    return "\n".join(inc) + "\n", "\n".join(pyi) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sdk-dir", default=os.environ.get("INSTA360_SDK_DIR"))
    ap.add_argument("--check", action="store_true", help="fail if outputs are out of date")
    args = ap.parse_args()
    if not args.sdk_dir:
        ap.error("--sdk-dir or INSTA360_SDK_DIR is required")
    inc, pyi = generate(args.sdk_dir)
    outputs = ((INC_OUT, inc), (PYI_OUT, pyi))
    if args.check:
        stale = [p for p, s in outputs if not p.exists() or p.read_text() != s]
        for p in stale:
            print("out of date: %s (rerun tools/gen_enums.py)" % p.relative_to(ROOT), file=sys.stderr)
        return 1 if stale else 0
    for path, content in outputs:
        path.write_text(content)
        print("wrote %s" % path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
